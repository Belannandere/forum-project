def get_text_for_title(title):
    """Возвращает осмысленный текст, соответствующий заголовку по ключевым словам."""
    title_lower = title.lower()
    for keyword, text in POST_CONTENT_MAP.items():
        if keyword in title_lower:
            return text
    # если не нашлось – вернуть универсальный текст
    return """
    <p>Уход за комнатными растениями – увлекательное занятие. Главное – соблюдать режим полива, освещения и температуры. Регулярно осматривайте листья на наличие вредителей. Не забывайте вовремя пересаживать и подкармливать. Каждое растение уникально, поэтому лучше заранее изучить его особенности.</p>
    <p>Делитесь своим опытом в комментариях! Вместе мы вырастим зелёный оазис в квартире.</p>
    """

def fix_all_posts():
    """Исправляет содержимое всех существующих постов, делая его осмысленным по заголовку."""
    with app.app_context():
        posts = Post.query.all()
        count = 0
        for post in posts:
            new_content = get_text_for_title(post.title)
            if post.content != new_content:
                post.content = new_content
                count += 1
        db.session.commit()
        print(f"Исправлено {count} постов (текст теперь соответствует теме).")

def seed_users(count=10):
    """Создаёт обычных пользователей, если их меньше count"""
    with app.app_context():
        existing = User.query.count()
        if existing >= count + 1:  # +1 админ
            print(f"Пользователей уже достаточно: {existing}")
            return
        
        admin = User.query.filter_by(role='admin').first()
        if not admin:
            admin = User(username='admin', email='admin@example.com', password_hash=generate_password_hash('admin'), role='admin')
            db.session.add(admin)
            db.session.commit()
            print("Администратор создан")
        
        new_count = count - existing + 1  # сколько нужно создать
        for i in range(new_count):
            username = f"user_{random.randint(100, 999)}"
            user = User(
                username=username,
                email=f"{username}@example.com",
                password_hash=generate_password_hash('password123'),
                bio=random.choice(["Люблю цветы и природу", "Садовод-любитель", "Зелёный энтузиаст"]),
                created_at=datetime.utcnow() - timedelta(days=random.randint(0, 365)),
                last_seen=datetime.utcnow() - timedelta(hours=random.randint(0, 72))
            )
            db.session.add(user)
        db.session.commit()
        print(f"Создано {new_count} новых пользователей.")

def seed_posts_and_comments(posts_count=25, comments_per_post_min=3, comments_per_post_max=10):
    with app.app_context():
        categories = Category.query.all()
        if not categories:
            print("Нет категорий. Запустите приложение хотя бы раз для их создания.")
            return
        users = User.query.filter(User.role != 'admin').all()
        if not users:
            print("Нет обычных пользователей, сначала выполните seed_users()")
            return
        
        existing_posts = Post.query.count()
        if existing_posts >= posts_count:
            print(f"Постов уже достаточно ({existing_posts}), пропускаем добавление новых.")
            fix_all_posts()  # но исправляем существующие
            return
        
        need_posts = posts_count - existing_posts
        print(f"Создаём {need_posts} новых постов с осмысленным текстом...")
        
        # Список осмысленных заголовков (взяты из KEYWORDS)
        good_titles = [
            "Как ухаживать за монстерой?",
            "Спасаем орхидею от вредителей",
            "Лучший грунт для суккулентов",
            "Зимний полив комнатных растений",
            "Фикус Бенджамина сбросил листья",
            "Как вырастить авокадо из косточки",
            "Борьба с мучнистым червецом",
            "Фитосветодиоды – какой выбрать?",
            "Что посадить на балконе?",
            "Вертикальное озеленение в квартире",
            "Эко-привычки: сортировка отходов",
            "Как привлечь пчёл в сад?",
            "Где купить редкие семена?",
            "Болезни рассады томатов",
            "Лунный календарь – миф или помощь?"
        ]
        
        created_posts = []
        for i in range(need_posts):
            author = random.choice(users)
            category = random.choice(categories)
            title = good_titles[i % len(good_titles)]
            if i >= len(good_titles):
                title += f" (часть {i//len(good_titles)+1})"
            slug = re.sub(r'[^a-z0-9-]', '', title.lower().replace(' ', '-').replace('?', '').replace('–', ''))
            slug = re.sub(r'-+', '-', slug).strip('-')
            orig_slug = slug
            counter = 1
            while Post.query.filter_by(slug=slug).first():
                slug = f"{orig_slug}-{counter}"
                counter += 1
            post = Post(
                title=title,
                slug=slug,
                content=get_text_for_title(title),
                user_id=author.id,
                category_id=category.id,
                views=random.randint(0, 500),
                likes=0,
                created_at=datetime.utcnow() - timedelta(days=random.randint(0, 60)),
                updated_at=datetime.utcnow() - timedelta(days=random.randint(0, 10))
            )
            db.session.add(post)
            created_posts.append(post)
        db.session.commit()
        print(f"Создано {len(created_posts)} постов")
        
        # комментарии (оставляем разумные случайные)
        all_comments = []
        for post in created_posts:
            num = random.randint(comments_per_post_min, comments_per_post_max)
            for _ in range(num):
                author = random.choice(users)
                comment = Comment(
                    content=f"<p>{random.choice(['Спасибо, очень полезно!', 'А можно подробнее про полив?', 'У меня та же проблема, помогло опрыскивание.', 'Супер, буду пробовать!', 'А где купить такие семена?', 'Спасибо автору!'])}</p>",
                    user_id=author.id,
                    post_id=post.id,
                    created_at=post.created_at + timedelta(minutes=random.randint(1, 2880)),
                    votes_total=random.randint(-2, 10)
                )
                db.session.add(comment)
                all_comments.append(comment)
        db.session.commit()
        print(f"Создано {len(all_comments)} комментариев")
        
        # Небольшие случайные лайки к постам
        for post in Post.query.all():
            for user in random.sample(users, min(random.randint(0, 5), len(users))):
                if not PostLike.query.filter_by(user_id=user.id, post_id=post.id).first():
                    like = PostLike(user_id=user.id, post_id=post.id)
                    db.session.add(like)
                    post.likes += 1
        db.session.commit()
        print("Лайки добавлены")

def run_seed():
    with app.app_context():
        seed_users(10)                # создаст пользователей
        seed_posts_and_comments(25, 2, 8)   # создаст посты с осмысленным текстом
        fix_all_posts()               # на всякий случай исправит старые посты (если есть)
        print("Готово! Теперь все тексты постов осмысленны и соответствуют темам.")

if __name__ == '__main__':
    run_seed()