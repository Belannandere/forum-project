def seed_with_quality_content():
    """Создаёт по 5 тем и по 5 комментариев под каждой для существующих категорий."""
    with app.app_context():
        # Получаем все категории из БД
        categories = Category.query.all()
        if not categories:
            print("Нет категорий. Сначала запустите приложение для их создания.")
            return

        users = User.query.filter(User.role != 'admin').all()
        if not users:
            print("Нет обычных пользователей. Создайте их через seed_users()")
            return

        # Для каждой категории ищем темы в словаре, если нет – пропускаем
        for category in categories:
            cat_key = category.slug
            cat_data = TOPICS_BY_CATEGORY.get(cat_key)
            if not cat_data:
                print(f"Для категории '{category.name}' нет заготовленных тем. Пропускаем.")
                continue

            topics_list = cat_data['topics']
            # Берём первые 5 тем (или все, если меньше)
            for topic_data in topics_list[:5]:
                # Проверим, нет ли уже поста с таким заголовком в этой категории
                existing = Post.query.filter_by(title=topic_data['title'], category_id=category.id).first()
                if existing:
                    print(f"Пост '{topic_data['title']}' уже существует, пропускаем.")
                    continue

                # Выбираем случайного автора
                author = random.choice(users)
                # Генерация слага
                slug = topic_data['title'].lower().replace(' ', '-').replace('?', '').replace(',', '').replace('ё', 'е')
                slug = slug[:200]  # ограничение длины
                # Уникальность слага
                final_slug = slug
                counter = 1
                while Post.query.filter_by(slug=final_slug).first():
                    final_slug = f"{slug}-{counter}"
                    counter += 1

                # Создаём пост
                post = Post(
                    title=topic_data['title'],
                    slug=final_slug,
                    content=topic_data['content'],
                    user_id=author.id,
                    category_id=category.id,
                    created_at=datetime.utcnow() - timedelta(days=random.randint(0, 60)),
                    updated_at=datetime.utcnow() - timedelta(days=random.randint(0, 10)),
                    views=random.randint(0, 200),
                    likes=0
                )
                db.session.add(post)
                db.session.flush()  # чтобы получить post.id

                # Добавляем комментарии
                comments_data = topic_data.get('comments', [])
                # Если комментариев меньше 5, повторяем некоторые, но лучше сразу 5
                num_comments = min(5, len(comments_data))
                for i in range(num_comments):
                    comment_author = random.choice(users)
                    comment_text = comments_data[i]
                    comment = Comment(
                        content=f"<p>{comment_text}</p>",
                        user_id=comment_author.id,
                        post_id=post.id,
                        created_at=post.created_at + timedelta(minutes=random.randint(1, 2880)),
                        votes_total=random.randint(0, 10)
                    )
                    db.session.add(comment)

            db.session.commit()
        print("Генерация качественных тем и комментариев завершена.")

def seed_users(count=10):
    """Создаёт обычных пользователей, если их меньше count (без дублирования)."""
    with app.app_context():
        existing = User.query.count()
        if existing >= count + 1:  # +1 админ
            print(f"Пользователей уже достаточно: {existing}")
            return

        # Создаём админа, если нет, через ensure_default_data, но лучше отдельно
        admin = User.query.filter_by(email='admin@example.com').first()
        if not admin:
            admin = User(
                username='admin',
                email='admin@example.com',
                password_hash=generate_password_hash('admin'),
                role='admin'
            )
            db.session.add(admin)
            db.session.commit()
            print("Администратор создан")
        else:
            # Обновляем роль и имя при необходимости
            if admin.role != 'admin':
                admin.role = 'admin'
                db.session.commit()

        # Сколько нужно создать обычных пользователей
        needed = count - (User.query.count() - 1)  # минус админ
        if needed <= 0:
            return

        # Список реалистичных имён и био
        names = ["Анна", "Мария", "Елена", "Дмитрий", "Алексей", "Ольга", "Иван", "Татьяна", "Сергей", "Наталья"]
        bios = [
            "Люблю цветы и делюсь опытом",
            "Садовод-любитель с 10-летним стажем",
            "Коллекционирую редкие растения",
            "Помогаю растениям расти здоровыми",
            "Зелёный энтузиаст, учусь каждый день"
        ]
        for i in range(needed):
            username = random.choice(names) + str(random.randint(10, 99))
            user = User(
                username=username,
                email=f"{username.lower()}@example.com",
                password_hash=generate_password_hash('password123'),
                bio=random.choice(bios),
                created_at=datetime.utcnow() - timedelta(days=random.randint(0, 365)),
                last_seen=datetime.utcnow() - timedelta(hours=random.randint(0, 72))
            )
            db.session.add(user)
        db.session.commit()
        print(f"Создано {needed} новых пользователей.")

